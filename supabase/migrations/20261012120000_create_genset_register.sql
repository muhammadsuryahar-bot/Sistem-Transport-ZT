-- Dedicated Genset register sourced from Data Kendaraan 07 Mei 2026.xlsx / Data Genset.
CREATE TABLE IF NOT EXISTS public.genset (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_no integer NOT NULL UNIQUE CHECK (source_no > 0),
  merk text NOT NULL CHECK (length(btrim(merk)) > 0),
  kapasitas_kva numeric NOT NULL CHECK (kapasitas_kva > 0),
  engine_no text,
  generator_no text,
  lokasi_kerja text,
  pemilik text,
  status_kepemilikan text NOT NULL CHECK (status_kepemilikan IN ('ASET','SEWA')),
  keterangan text,
  source_file text,
  source_sheet text,
  source_row integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.genset ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.genset TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.genset_id_seq TO authenticated;

CREATE POLICY genset_select_transport_admin
  ON public.genset FOR SELECT TO authenticated
  USING (private.has_any_role(ARRAY['ADMIN'::public.user_role, 'TRANSPORT'::public.user_role]));
CREATE POLICY genset_insert_transport_admin
  ON public.genset FOR INSERT TO authenticated
  WITH CHECK (private.has_any_role(ARRAY['ADMIN'::public.user_role, 'TRANSPORT'::public.user_role]));
CREATE POLICY genset_update_transport_admin
  ON public.genset FOR UPDATE TO authenticated
  USING (private.has_any_role(ARRAY['ADMIN'::public.user_role, 'TRANSPORT'::public.user_role]))
  WITH CHECK (private.has_any_role(ARRAY['ADMIN'::public.user_role, 'TRANSPORT'::public.user_role]));
CREATE POLICY genset_delete_admin
  ON public.genset FOR DELETE TO authenticated
  USING (private.has_any_role(ARRAY['ADMIN'::public.user_role]));

